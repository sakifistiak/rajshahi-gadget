<p>This Return &amp; Refund Policy explains when a product bought from <strong>Khan Gadget</strong> can be returned, replaced or refunded, and how long it takes.</p>

<h2>1. Refund timeline</h2>
<p>Once a refund claim is approved, the refund is completed within <strong>7-10 working days</strong>. The money is sent back through the original payment method (card, mobile banking or bank transfer). For Cash on Delivery orders, the refund is sent by bKash, Nagad or bank transfer to an account the customer provides.</p>

<h2>2. When you can claim a return or refund</h2>
<ul>
    <li>The product delivered is wrong (different model or specification from your order).</li>
    <li>The product is defective or damaged on arrival.</li>
    <li>The order was paid for but could not be delivered, or the product is out of stock after payment.</li>
    <li>The order was cancelled by you before it was shipped (see Cancellation below).</li>
</ul>
<p>A return or refund must be claimed within <strong>7 days</strong> of receiving the product. Please contact us by phone or email with your order number and photos or a video of the problem.</p>

<h2>3. Return conditions</h2>
<ul>
    <li>The product must be returned with its original box, accessories, charger, invoice and gifts (if any).</li>
    <li>Serial numbers and warranty stickers must be intact.</li>
    <li>Physical damage, liquid damage, burn marks or repair attempts after delivery are not eligible for return or refund.</li>
    <li>A change of mind after the product has been delivered and used is not eligible for a refund.</li>
</ul>

<h2>4. Return and refund process</h2>
<ol>
    <li>Contact us with your order number and the reason for the claim.</li>
    <li>Our team checks the claim and, if needed, the product (usually within 2-3 working days of receiving it).</li>
    <li>If the claim is approved, we replace the product or refund the money, as you prefer.</li>
    <li>The refund is completed within <strong>7-10 working days</strong> after approval.</li>
</ol>

<h2>5. Cancellation policy</h2>
<p>An order can be cancelled free of charge any time before it is shipped. If an online payment was made, the full amount is refunded within <strong>7-10 working days</strong>. Once the order has been shipped, it cannot be cancelled, but it can still be returned under the conditions above.</p>

<h2>6. Delivery time</h2>
<ul>
    <li><strong>Inside Dhaka:</strong> within 5 days</li>
    <li><strong>Outside Dhaka:</strong> within 10 days</li>
</ul>

